// Convert Raw Projected Coordinates to SVG Viewport [0..800, 0..800]
// X domain: [-1200 .. 10200] => [30 .. 770]
// Y domain: [-1100 .. 10200] => [770 .. 30] (Inverted for SVG Y-axis)

function transformCoord([x, y]: number[]): [number, number] {
  const minX = -1200;
  const maxX = 10200;
  const minY = -1100;
  const maxY = 10200;

  const svgX = 30 + ((x - minX) / (maxX - minX)) * 740;
  const svgY = 770 - ((y - minY) / (maxY - minY)) * 740;

  return [Math.round(svgX * 10) / 10, Math.round(svgY * 10) / 10];
}

function convertPolygon(rawCoords: number[][]): string {
  const transformed = rawCoords.map(transformCoord);
  return transformed.map(([x, y], i) => `${i === 0 ? 'M' : 'L'} ${x},${y}`).join(' ') + ' Z';
}

function calculateCentroid(rawCoords: number[][]): [number, number] {
  const transformed = rawCoords.map(transformCoord);
  let sumX = 0;
  let sumY = 0;
  transformed.forEach(([x, y]) => {
    sumX += x;
    sumY += y;
  });
  return [
    Math.round((sumX / transformed.length) * 10) / 10,
    Math.round((sumY / transformed.length) * 10) / 10,
  ];
}

